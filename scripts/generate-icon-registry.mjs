#!/usr/bin/env node
/**
 * Generate static SVG imports for board tiles.
 * Metro needs static `import … from '*.svg'` — do not hand-edit the output.
 *
 * Usage: node scripts/generate-icon-registry.mjs
 * npm:  npm run icons:generate
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(__dirname, '..');
const dirs = [
  path.join(root, 'city-icons', 'generic'),
  path.join(root, 'city-icons', 'icons'),
];
const outFile = path.join(
  root,
  'components',
  'board',
  'iconRegistry.generated.ts',
);

function walkSvgs(dir) {
  if (!fs.existsSync(dir)) {
    return [];
  }
  return fs
    .readdirSync(dir)
    .filter((name) => name.endsWith('.svg'))
    .map((name) => path.join(dir, name))
    .sort((a, b) => a.localeCompare(b));
}

function relKey(absPath) {
  return path.relative(root, absPath).split(path.sep).join('/');
}

function importId(rel) {
  // city-icons/icons/in-agra.svg → Icon_city_icons_icons_in_agra
  const stem = rel.replace(/\.svg$/i, '');
  const safe = stem.replace(/[^a-zA-Z0-9]+/g, '_');
  return `Icon_${safe}`;
}

const files = dirs.flatMap(walkSvgs);
if (files.length === 0) {
  console.error('No SVG files found under city-icons/');
  process.exit(1);
}

const entries = files.map((abs) => {
  const key = relKey(abs);
  return { key, id: importId(key), importPath: `@/${key}` };
});

// Dedupe ids if any collision (unlikely)
const seen = new Map();
for (const e of entries) {
  if (seen.has(e.id)) {
    let n = 2;
    while (seen.has(`${e.id}_${n}`)) {
      n += 1;
    }
    e.id = `${e.id}_${n}`;
  }
  seen.set(e.id, e.key);
}

const lines = [];
lines.push('/* eslint-disable */');
lines.push('/**');
lines.push(' * AUTO-GENERATED by scripts/generate-icon-registry.mjs');
lines.push(' * Do not edit. Run: npm run icons:generate');
lines.push(` * Icons: ${entries.length}`);
lines.push(' */');
lines.push('');
lines.push("import type { FC } from 'react';");
lines.push("import type { SvgProps } from 'react-native-svg';");
lines.push('');

for (const e of entries) {
  lines.push(`import ${e.id} from '${e.importPath}';`);
}

lines.push('');
lines.push('export type BoardIcon = FC<SvgProps>;');
lines.push('');
lines.push('export const iconRegistry: Record<string, BoardIcon> = {');
for (const e of entries) {
  lines.push(`  '${e.key}': ${e.id},`);
}
lines.push('};');
lines.push('');

fs.mkdirSync(path.dirname(outFile), { recursive: true });
fs.writeFileSync(outFile, lines.join('\n'), 'utf8');
console.log(`Wrote ${entries.length} icons → ${path.relative(root, outFile)}`);
